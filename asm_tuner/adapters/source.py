from __future__ import annotations

import json
from typing import List, Sequence

from ..schema import KernelConfig, StoreMode


_HEADER = r'''// Generated by GEAK asm_tuner. Do not edit generated shards.
// Algorithmic provenance is pinned in asm_tuner/PROVENANCE.json. No experiment
// directory is read by this source or its Python adapter at runtime.
#include <hip/hip_runtime.h>
#include <rocwmma/rocwmma.hpp>
#include <cstdint>

using InputT = @INPUT_TYPE@;
using OutputT = rocwmma::bfloat16_t;
constexpr int kMfmaM = 16;
constexpr int kMfmaN = 16;
constexpr int kMfmaK = @MFMA_K@;
constexpr bool kScaled = @SCALED@;
using FragA = rocwmma::fragment<rocwmma::matrix_a, 16, 16, kMfmaK, InputT, rocwmma::row_major>;
using FragB = rocwmma::fragment<rocwmma::matrix_b, 16, 16, kMfmaK, InputT, rocwmma::col_major>;
using FragC = rocwmma::fragment<rocwmma::accumulator, 16, 16, kMfmaK, float>;

template <int ElementBytes, int V>
struct RawPackType;
template <int V>
struct RawPackType<1, V> { using type = unsigned char __attribute__((ext_vector_type(V))); };
template <int V>
struct RawPackType<2, V> { using type = unsigned short __attribute__((ext_vector_type(V))); };

template <typename T, int V>
using Pack = typename RawPackType<sizeof(T), V>::type;

template <typename T, int V>
__device__ __forceinline__ Pack<T, V> guarded_load(
    const T* ptr, bool row_valid, int remaining) {
    Pack<T, V> value{};
    const auto address = reinterpret_cast<std::uintptr_t>(ptr);
    if (row_valid && remaining >= V && (address % alignof(Pack<T, V>) == 0)) {
        return *reinterpret_cast<const Pack<T, V>*>(ptr);
    }
    if (row_valid) {
#pragma unroll
        for (int e = 0; e < V; ++e) {
            if (e < remaining) {
                if constexpr (sizeof(T) == 1) {
                    value[e] = *reinterpret_cast<const unsigned char*>(ptr + e);
                } else {
                    value[e] = *reinterpret_cast<const unsigned short*>(ptr + e);
                }
            }
        }
    }
    return value;
}

template <int BM, int BN, int BK, int WAVES_M, int WAVES_N,
          int A_BUFFERS, int B_BUFFERS, int A_PAD, int B_PAD,
          int VWA, int VWB, int VWS, int WGM, int STAGGER, int PGR,
          bool NON_TEMPORAL>
__device__ __forceinline__ void gemm_body(
    int m, int n, int k,
    const InputT* __restrict__ a, const InputT* __restrict__ b,
    const float* __restrict__ a_scale, const float* __restrict__ b_scale,
    OutputT* __restrict__ c, unsigned char* __restrict__ smem) {
    constexpr int NW = WAVES_M * WAVES_N;
    constexpr int NT = NW * 64;
    constexpr int LDA = BK + A_PAD;
    constexpr int LDB = BK + B_PAD;
    constexpr int A_SLOT = BM * LDA;
    constexpr int B_SLOT = BN * LDB;
    constexpr int A_TOTAL = A_BUFFERS * A_SLOT;
    constexpr int B_TOTAL = B_BUFFERS * B_SLOT;
    constexpr int TM = BM / (WAVES_M * kMfmaM);
    constexpr int TN = BN / (WAVES_N * kMfmaN);
    constexpr int A_CHUNKS_PER_ROW = BK / VWA;
    constexpr int B_CHUNKS_PER_ROW = BK / VWB;
    constexpr int A_CHUNKS = BM * A_CHUNKS_PER_ROW;
    constexpr int B_CHUNKS = BN * B_CHUNKS_PER_ROW;
    constexpr int A_PREFETCH_PACKS = (A_CHUNKS + NT - 1) / NT;
    constexpr int B_PREFETCH_PACKS = (B_CHUNKS + NT - 1) / NT;
    static_assert(BM % (WAVES_M * kMfmaM) == 0, "invalid M wave tile");
    static_assert(BN % (WAVES_N * kMfmaN) == 0, "invalid N wave tile");
    static_assert(BK % kMfmaK == 0, "invalid K tile");
    static_assert(kMfmaN % VWS == 0, "store vector crosses fragment rows");
    static_assert(PGR == 1 || PGR == 2, "only PGR1 and PGR2 are implemented");

    const int block = static_cast<int>(blockIdx.x);
    const int gx = (n + BN - 1) / BN;
    const int gy = (m + BM - 1) / BM;
    const int full_groups = gx / WGM;
    const int full_blocks = full_groups * WGM * gy;
    int tile_m;
    int tile_n;
    if (block < full_blocks) {
        const int span = WGM * gy;
        const int group = block / span;
        const int inside = block - group * span;
        tile_n = group * WGM + inside % WGM;
        tile_m = inside / WGM;
    } else {
        const int tail = gx - full_groups * WGM;
        const int inside = block - full_blocks;
        tile_n = full_groups * WGM + inside % tail;
        tile_m = inside / tail;
    }

    const int row0 = tile_m * BM;
    const int col0 = tile_n * BN;
    const int tid = static_cast<int>(threadIdx.x);
    const int wave = tid >> 6;
    const int lane = tid & 63;
    const int wm = wave / WAVES_N;
    const int wn = wave % WAVES_N;
    InputT* const a_base = reinterpret_cast<InputT*>(smem);
    InputT* const b_base = a_base + A_TOTAL;
    float* const epilogue = reinterpret_cast<float*>(b_base + B_TOTAL);

    FragC acc[TM][TN];
#pragma unroll
    for (int i = 0; i < TM; ++i) {
#pragma unroll
        for (int j = 0; j < TN; ++j) rocwmma::fill_fragment(acc[i][j], 0.0f);
    }

    const int stages = (k + BK - 1) / BK;
    int stage_shift = 0;
    if constexpr (STAGGER > 0) stage_shift = block % (STAGGER < stages ? STAGGER : stages);

    // PGR2 owns exactly one future global stage in ordinary registers. It does
    // not add an LDS slot: A_BUFFERS=B_BUFFERS=1 remains a valid pipeline.
    Pack<InputT, VWA> a_prefetch[A_PREFETCH_PACKS];
    Pack<InputT, VWB> b_prefetch[B_PREFETCH_PACKS];
    if constexpr (PGR == 2) {
        const int first_stage = stage_shift;
        const int first_k0 = first_stage * BK;
#pragma unroll
        for (int slot = 0; slot < A_PREFETCH_PACKS; ++slot) {
            const int chunk = tid + slot * NT;
            a_prefetch[slot] = Pack<InputT, VWA>{};
            if (chunk < A_CHUNKS) {
                const int row = chunk / A_CHUNKS_PER_ROW;
                const int kk = (chunk % A_CHUNKS_PER_ROW) * VWA;
                const bool valid = row0 + row < m;
                const InputT* src = valid ? a + static_cast<long>(row0 + row) * k + first_k0 + kk : a;
                a_prefetch[slot] = guarded_load<InputT, VWA>(src, valid, k - first_k0 - kk);
            }
        }
#pragma unroll
        for (int slot = 0; slot < B_PREFETCH_PACKS; ++slot) {
            const int chunk = tid + slot * NT;
            b_prefetch[slot] = Pack<InputT, VWB>{};
            if (chunk < B_CHUNKS) {
                const int row = chunk / B_CHUNKS_PER_ROW;
                const int kk = (chunk % B_CHUNKS_PER_ROW) * VWB;
                const bool valid = col0 + row < n;
                const InputT* src = valid ? b + static_cast<long>(col0 + row) * k + first_k0 + kk : b;
                b_prefetch[slot] = guarded_load<InputT, VWB>(src, valid, k - first_k0 - kk);
            }
        }
    }

    for (int logical_stage = 0; logical_stage < stages; ++logical_stage) {
        int stage = logical_stage + stage_shift;
        if (stage >= stages) stage -= stages;
        const int k0 = stage * BK;
        InputT* const sA = a_base + (stage % A_BUFFERS) * A_SLOT;
        InputT* const sB = b_base + (stage % B_BUFFERS) * B_SLOT;

        if constexpr (PGR == 1) {
            for (int chunk = tid; chunk < A_CHUNKS; chunk += NT) {
                const int row = chunk / A_CHUNKS_PER_ROW;
                const int kk = (chunk % A_CHUNKS_PER_ROW) * VWA;
                const bool valid = row0 + row < m;
                const InputT* src = valid ? a + static_cast<long>(row0 + row) * k + k0 + kk : a;
                const auto value = guarded_load<InputT, VWA>(src, valid, k - k0 - kk);
                *reinterpret_cast<Pack<InputT, VWA>*>(sA + row * LDA + kk) = value;
            }
            for (int chunk = tid; chunk < B_CHUNKS; chunk += NT) {
                const int row = chunk / B_CHUNKS_PER_ROW;
                const int kk = (chunk % B_CHUNKS_PER_ROW) * VWB;
                const bool valid = col0 + row < n;
                const InputT* src = valid ? b + static_cast<long>(col0 + row) * k + k0 + kk : b;
                const auto value = guarded_load<InputT, VWB>(src, valid, k - k0 - kk);
                *reinterpret_cast<Pack<InputT, VWB>*>(sB + row * LDB + kk) = value;
            }
        } else {
#pragma unroll
            for (int slot = 0; slot < A_PREFETCH_PACKS; ++slot) {
                const int chunk = tid + slot * NT;
                if (chunk < A_CHUNKS) {
                    const int row = chunk / A_CHUNKS_PER_ROW;
                    const int kk = (chunk % A_CHUNKS_PER_ROW) * VWA;
                    *reinterpret_cast<Pack<InputT, VWA>*>(sA + row * LDA + kk) = a_prefetch[slot];
                }
            }
#pragma unroll
            for (int slot = 0; slot < B_PREFETCH_PACKS; ++slot) {
                const int chunk = tid + slot * NT;
                if (chunk < B_CHUNKS) {
                    const int row = chunk / B_CHUNKS_PER_ROW;
                    const int kk = (chunk % B_CHUNKS_PER_ROW) * VWB;
                    *reinterpret_cast<Pack<InputT, VWB>*>(sB + row * LDB + kk) = b_prefetch[slot];
                }
            }
        }
        __syncthreads();

        if constexpr (PGR == 2) {
            if (logical_stage + 1 < stages) {
                int next_stage = logical_stage + 1 + stage_shift;
                if (next_stage >= stages) next_stage -= stages;
                const int next_k0 = next_stage * BK;
                // These global loads are intentionally issued before current
                // LDS reads/MFMA. Their values stay live until the next loop.
#pragma unroll
                for (int slot = 0; slot < A_PREFETCH_PACKS; ++slot) {
                    const int chunk = tid + slot * NT;
                    a_prefetch[slot] = Pack<InputT, VWA>{};
                    if (chunk < A_CHUNKS) {
                        const int row = chunk / A_CHUNKS_PER_ROW;
                        const int kk = (chunk % A_CHUNKS_PER_ROW) * VWA;
                        const bool valid = row0 + row < m;
                        const InputT* src = valid ? a + static_cast<long>(row0 + row) * k + next_k0 + kk : a;
                        a_prefetch[slot] = guarded_load<InputT, VWA>(src, valid, k - next_k0 - kk);
                    }
                }
#pragma unroll
                for (int slot = 0; slot < B_PREFETCH_PACKS; ++slot) {
                    const int chunk = tid + slot * NT;
                    b_prefetch[slot] = Pack<InputT, VWB>{};
                    if (chunk < B_CHUNKS) {
                        const int row = chunk / B_CHUNKS_PER_ROW;
                        const int kk = (chunk % B_CHUNKS_PER_ROW) * VWB;
                        const bool valid = col0 + row < n;
                        const InputT* src = valid ? b + static_cast<long>(col0 + row) * k + next_k0 + kk : b;
                        b_prefetch[slot] = guarded_load<InputT, VWB>(src, valid, k - next_k0 - kk);
                    }
                }
            }
        }

#pragma unroll
        for (int sk = 0; sk < BK; sk += kMfmaK) {
            FragA fa[TM];
            FragB fb[TN];
#pragma unroll
            for (int i = 0; i < TM; ++i)
                rocwmma::load_matrix_sync(fa[i], sA + (wm * TM + i) * kMfmaM * LDA + sk, LDA);
#pragma unroll
            for (int j = 0; j < TN; ++j)
                rocwmma::load_matrix_sync(fb[j], sB + (wn * TN + j) * kMfmaN * LDB + sk, LDB);
#pragma unroll
            for (int i = 0; i < TM; ++i) {
#pragma unroll
                for (int j = 0; j < TN; ++j) rocwmma::mma_sync(acc[i][j], fa[i], fb[j], acc[i][j]);
            }
        }
        __syncthreads();
    }

    float* const wave_out = epilogue + wave * kMfmaM * kMfmaN;
#pragma unroll
    for (int i = 0; i < TM; ++i) {
#pragma unroll
        for (int j = 0; j < TN; ++j) {
            rocwmma::store_matrix_sync(wave_out, acc[i][j], kMfmaN, rocwmma::mem_row_major);
            __syncthreads();
            for (int linear = lane * VWS; linear < kMfmaM * kMfmaN; linear += 64 * VWS) {
                const int local_row = linear / kMfmaN;
                const int local_col = linear % kMfmaN;
                const int row = row0 + (wm * TM + i) * kMfmaM + local_row;
                const int col = col0 + (wn * TN + j) * kMfmaN + local_col;
                const bool vector_valid = row < m && col + VWS <= n;
                OutputT* dst = vector_valid ? c + static_cast<long>(row) * n + col : c;
                if (vector_valid && !NON_TEMPORAL &&
                    reinterpret_cast<std::uintptr_t>(dst) % alignof(Pack<OutputT, VWS>) == 0) {
                    Pack<OutputT, VWS> out{};
#pragma unroll
                    for (int e = 0; e < VWS; ++e) {
                        float value = wave_out[linear + e];
                        if constexpr (kScaled) value *= a_scale[row] * b_scale[col + e];
                        const OutputT converted(value);
                        out[e] = *reinterpret_cast<const unsigned short*>(&converted);
                    }
                    *reinterpret_cast<Pack<OutputT, VWS>*>(dst) = out;
                } else {
#pragma unroll
                    for (int e = 0; e < VWS; ++e) {
                        if (row < m && col + e < n) {
                            float value = wave_out[linear + e];
                            if constexpr (kScaled) value *= a_scale[row] * b_scale[col + e];
                            const OutputT out(value);
                            if constexpr (NON_TEMPORAL) {
                                __builtin_nontemporal_store(
                                    *reinterpret_cast<const unsigned short*>(&out),
                                    reinterpret_cast<unsigned short*>(c + static_cast<long>(row) * n + col + e));
                            } else {
                                c[static_cast<long>(row) * n + col + e] = out;
                            }
                        }
                    }
                }
            }
            __syncthreads();
        }
    }
}
'''


def _entry(config: KernelConfig, adapter_name: str, arch_guard: str) -> str:
    kernel = "geak_%s_%s" % (adapter_name, config.config_id)
    launch = "geak_launch_%s_%s" % (adapter_name, config.config_id)
    non_temporal = "true" if config.store.mode is StoreMode.NON_TEMPORAL else "false"
    template_args = ", ".join(str(value) for value in (
        config.bm, config.bn, config.bk, config.wave_grid.m, config.wave_grid.n,
        config.a_lds.buffers, config.b_lds.buffers, config.a_lds.pad_elements,
        config.b_lds.pad_elements, config.vector_widths.a, config.vector_widths.b,
        config.vector_widths.store, config.wgm, config.stagger, config.pgr,
    )) + ", " + non_temporal
    config_json = json.dumps(config.to_dict(include_derived=True), sort_keys=True, separators=(",", ":"))
    source = r'''
// CONFIG @CONFIG_JSON@
// PGR=@PGR@ is executable; PLR=@PLR@ remains fail-closed in source_version rocwmma-pgr2-v2.
extern "C" __global__ __launch_bounds__(@THREADS@, 1)
void @KERNEL@(
    int m, int n, int k, const InputT* a, const InputT* b,
    const float* a_scale, const float* b_scale, OutputT* c) {
#if @ARCH_GUARD@
    __shared__ __align__(16) unsigned char smem[@LDS_BYTES@];
    gemm_body<@TEMPLATE_ARGS@>(m, n, k, a, b, a_scale, b_scale, c, smem);
#else
    (void)m; (void)n; (void)k; (void)a; (void)b; (void)a_scale; (void)b_scale; (void)c;
#endif
}

extern "C" int @LAUNCH@(
    int m, int n, int k, const void* a, const void* b,
    const float* a_scale, const float* b_scale, void* c, void* stream) {
    const int gx = (n + @BN@ - 1) / @BN@;
    const int gy = (m + @BM@ - 1) / @BM@;
    hipLaunchKernelGGL((@KERNEL@), dim3(gx * gy), dim3(@THREADS@), 0,
                       static_cast<hipStream_t>(stream), m, n, k,
                       static_cast<const InputT*>(a), static_cast<const InputT*>(b),
                       a_scale, b_scale, static_cast<OutputT*>(c));
    return static_cast<int>(hipGetLastError());
}
'''
    replacements = {
        "@CONFIG_JSON@": config_json, "@PGR@": str(config.pgr), "@PLR@": str(config.plr),
        "@THREADS@": str(config.nw * 64), "@KERNEL@": kernel, "@LAUNCH@": launch,
        "@ARCH_GUARD@": arch_guard, "@LDS_BYTES@": str(config.lds.total_bytes),
        "@TEMPLATE_ARGS@": template_args, "@BN@": str(config.bn), "@BM@": str(config.bm),
    }
    for old, new in replacements.items():
        source = source.replace(old, new)
    return source


def render_rocwmma_source(
    adapter_name: str,
    configs: Sequence[KernelConfig],
    input_type: str,
    mfma_k: int,
    scaled: bool,
) -> str:
    if not configs:
        raise ValueError("cannot render an empty shard")
    arch = configs[0].arch
    if any(config.arch is not arch for config in configs):
        raise ValueError("one compile shard cannot mix architectures")
    guard = "defined(__%s__)" % arch.value
    header = _HEADER.replace("@INPUT_TYPE@", input_type).replace("@MFMA_K@", str(mfma_k)).replace(
        "@SCALED@", "true" if scaled else "false"
    )
    entries: List[str] = [_entry(config, adapter_name, guard) for config in configs]
    return header + "\n".join(entries)
